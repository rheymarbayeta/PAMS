/* Shared Rights & Rentals report rendering utilities */
(function (global) {
  'use strict';

  var REPORT_TITLES = {
    contracts: 'LEASE CONTRACTS REPORT',
    payments: 'PAYMENT COLLECTION REPORT',
    outstanding: 'OUTSTANDING BALANCES REPORT'
  };

  var REPORT_SUBTITLES = {
    contracts: 'Summary of lease agreements, financial terms, and payment totals',
    payments: 'Detailed listing of rights and rental payments collected',
    outstanding: 'Contracts with remaining rights balance or outstanding rental'
  };

  function fmtCurrency(n) {
    return Number(n || 0).toLocaleString('en-PH', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }

  function fmtDate(s) {
    if (!s) return '—';
    var d = new Date(s);
    if (isNaN(d.getTime())) return s;
    return d.toLocaleDateString('en-PH', { year: 'numeric', month: 'short', day: 'numeric' });
  }

  function esc(str) {
    var d = document.createElement('div');
    d.appendChild(document.createTextNode(str == null ? '' : String(str)));
    return d.innerHTML;
  }

  function getLogoUrl(apiBase, url) {
    if (!url) return null;
    if (url.startsWith('http')) return url;
    if (url.startsWith('/api/')) return apiBase + url;
    return url;
  }

  function buildAssessmentHeaderHTML(settings, apiBase) {
    var pfx = 'assessment_header';
    var logoLeft = getLogoUrl(apiBase, settings[pfx + '_logo_left']?.value) || '/dalaguete-logo.png';
    var logoRight = getLogoUrl(apiBase, settings[pfx + '_logo_right']?.value);
    var logoH = Math.max(20, Math.min(120, parseFloat(settings[pfx + '_logo_size']?.value) || 50));
    var fs = Math.max(7, Math.min(20, parseFloat(settings[pfx + '_font_size']?.value) || 11));
    var l1 = settings[pfx + '_line_1']?.value || 'REPUBLIC OF THE PHILIPPINES';
    var l2 = settings[pfx + '_line_2']?.value || 'MUNICIPALITY OF DALAGUETE';
    var l3 = settings[pfx + '_line_3']?.value || 'PROVINCE OF CEBU';
    var l4 = settings[pfx + '_line_4']?.value || "MUNICIPAL TREASURER'S OFFICE";
    var l5 = settings[pfx + '_line_5']?.value || '';

    return (
      '<div style="text-align:center;margin-bottom:14px;">' +
      '<div style="display:flex;justify-content:center;align-items:center;gap:16px;margin-bottom:6px;">' +
      (logoLeft ? '<img src="' + logoLeft + '" alt="Logo" style="height:' + logoH + 'px;width:auto;object-fit:contain;">' : '') +
      '<div style="text-align:center;line-height:1.2;">' +
      (l1 ? '<div style="font-size:' + fs + 'px;font-weight:bold;">' + esc(l1) + '</div>' : '') +
      (l2 ? '<div style="font-size:' + fs + 'px;font-weight:bold;">' + esc(l2) + '</div>' : '') +
      (l3 ? '<div style="font-size:' + fs + 'px;font-weight:bold;">' + esc(l3) + '</div>' : '') +
      (l4 ? '<div style="font-size:' + Math.round(fs * 1.45) + 'px;font-weight:bold;margin-top:2px;">' + esc(l4) + '</div>' : '') +
      (l5 ? '<div style="font-size:' + fs + 'px;font-weight:bold;margin-top:2px;">' + esc(l5) + '</div>' : '') +
      '</div>' +
      (logoRight ? '<img src="' + logoRight + '" alt="Logo 2" style="height:' + logoH + 'px;width:auto;object-fit:contain;">' : '') +
      '</div>' +
      '<div style="border-bottom:2px solid #333;margin-top:6px;"></div>' +
      '</div>'
    );
  }

  function buildFooterHTML(userName, issuedAt) {
    return (
      '<div>Generated by: ' +
      esc(userName) +
      ' | Permit and Assessment Management System | Issued: ' +
      esc(issuedAt) +
      ' | Page <span class="page-number"></span> of <span class="total-pages"></span></div>'
    );
  }

  function buildSignatoryHTML(settings, userName, apiBase) {
    if (settings.citation_signatory_enabled?.value === 'false') return '';
    var preparedPos = settings.citation_prepared_by_position?.value || '';
    var certName = settings.citation_certified_by_name?.value || '';
    var certPos = settings.citation_certified_by_position?.value || '';
    var certSig = getLogoUrl(apiBase, settings.citation_certified_by_signature?.value);
    var certImg = certSig
      ? '<img src="' + certSig + '" alt="E-Signature" style="height:36px;width:auto;max-width:140px;object-fit:contain;display:block;margin:0 auto 4px;">'
      : '';

    return (
      '<div class="signatory-block">' +
      '<table><tr>' +
      '<td><div class="sig-label">Prepared by:</div><div class="sig-line">' +
      '<div class="sig-name">' + esc(userName) + '</div>' +
      '<div class="sig-position">' + esc(preparedPos) + '</div></div></td>' +
      '<td><div class="sig-label">Certified correct by:</div><div class="sig-line">' +
      certImg +
      '<div class="sig-name">' + esc(certName) + '</div>' +
      '<div class="sig-position">' + esc(certPos) + '</div></div></td>' +
      '</tr></table></div>'
    );
  }

  function buildFilterLabel(filters) {
    var parts = [];
    if (filters.reportType) parts.push('Report: ' + (REPORT_TITLES[filters.reportType] || filters.reportType));
    if (filters.propertyId) parts.push('Property ID: ' + filters.propertyId);
    if (filters.propertyName) parts.push('Property: ' + filters.propertyName);
    if (filters.status) parts.push('Status: ' + filters.status);
    if (filters.paymentType && filters.paymentType !== 'all') parts.push('Payment: ' + filters.paymentType);
    if (filters.floorLevel) parts.push('Floor: ' + filters.floorLevel);
    if (filters.dateFrom) parts.push('From: ' + filters.dateFrom);
    if (filters.dateTo) parts.push('To: ' + filters.dateTo);
    if (filters.search) parts.push('Search: "' + filters.search + '"');
    return parts.length ? parts.join('  |  ') : 'All Records';
  }

  function buildSummaryHTML(reportType, summary) {
    if (!summary) return '';
    var lines = [];

    if (reportType === 'payments') {
      lines.push('Total Payments: ' + (summary.totalRecords || 0));
      lines.push('Rights Payments: ' + (summary.rightsPayments || 0) + ' — ₱ ' + fmtCurrency(summary.totalRightsCollected));
      lines.push('Rental Payments: ' + (summary.rentalPayments || 0) + ' — ₱ ' + fmtCurrency(summary.totalRentalCollected));
      lines.push('Grand Total Collected: ₱ ' + fmtCurrency(summary.grandTotalCollected));
    } else if (reportType === 'outstanding') {
      lines.push('Contracts with Balance: ' + (summary.totalRecords || 0));
      lines.push('Total Rights Balance: ₱ ' + fmtCurrency(summary.totalRightsBalance));
      lines.push('Total Outstanding Rental: ₱ ' + fmtCurrency(summary.totalOutstandingRental));
      lines.push('Combined Monthly Dues: ₱ ' + fmtCurrency(summary.totalMonthlyDues));
    } else {
      lines.push('Total Contracts: ' + (summary.totalRecords || 0));
      lines.push('Active Contracts: ' + (summary.activeContracts || 0));
      lines.push('Total Principal: ₱ ' + fmtCurrency(summary.totalPrincipal));
      lines.push('Rights Collected: ₱ ' + fmtCurrency(summary.totalRightsCollected));
      lines.push('Rental Collected: ₱ ' + fmtCurrency(summary.totalRentalCollected));
      lines.push('Rights Balance Remaining: ₱ ' + fmtCurrency(summary.totalRightsBalance));
    }

    return '<div class="summary-box"><strong>Summary</strong><br>' + lines.map(esc).join('<br>') + '</div>';
  }

  function updatePageNumbers() {
    var pages = document.querySelectorAll('.page');
    var total = pages.length;
    pages.forEach(function (page, idx) {
      var num = page.querySelector('.page-number');
      var tot = page.querySelector('.total-pages');
      if (num) num.textContent = String(idx + 1);
      if (tot) tot.textContent = String(total);
    });
  }

  global.RRReportCommon = {
    REPORT_TITLES: REPORT_TITLES,
    REPORT_SUBTITLES: REPORT_SUBTITLES,
    fmtCurrency: fmtCurrency,
    fmtDate: fmtDate,
    esc: esc,
    buildAssessmentHeaderHTML: buildAssessmentHeaderHTML,
    buildFooterHTML: buildFooterHTML,
    buildSignatoryHTML: buildSignatoryHTML,
    buildFilterLabel: buildFilterLabel,
    buildSummaryHTML: buildSummaryHTML,
    updatePageNumbers: updatePageNumbers
  };
})(typeof window !== 'undefined' ? window : this);
